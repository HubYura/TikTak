const DAYS = ['Понеділок', 'Середа', 'П’ятниця'];

/** Помилки, над якими варто працювати, — від найчастішої. */
export function weakTraps(p: Progress): Trap[] {
  return TRAPS.filter(t => isWeak(p.traps[t])).sort((a, b) => weakness(p.traps[b]) - weakness(p.traps[a]));
}

export function homePlan(p: Progress): HomePlan {
  const weak = weakTraps(p).slice(0, 2);
  let focus: string, acts: Activity[];
  if (weak.length) {
    const main = BY_TRAP[weak[0]];
    focus = 'Цього тижня — ' + main.focus + (weak[1] ? '; трохи — ' + BY_TRAP[weak[1]].focus : '') + '.';
    // Головна помилка — двічі, друга (якщо є) — раз; інакше обидві вправи головної й повтор першої
    acts = weak[1] ? [main.acts[0], BY_TRAP[weak[1]].acts[0], main.acts[1]] : [main.acts[0], main.acts[1], main.acts[0]];
  } else {
    const lv = BY_LEVEL[Math.min(p.unlocked, BY_LEVEL.length - 1)];
    focus = 'Стійких помилок нема — цього тижня закріплюємо ' + lv.focus + ' (' + LEVELS[Math.min(p.unlocked, LEVELS.length - 1)].name + ').';
    acts = [lv.acts[0], lv.acts[1], lv.acts[0]];
  }
  return {
    focus,
    items: acts.map((a, i) => ({ ...a, day: DAYS[i], minutes: 5 })),
    daily: 'Щодня: тричі на день називайте час уголос, прив’язуючи до подій — «зараз пів на восьму, час до школи».'
  };
}
